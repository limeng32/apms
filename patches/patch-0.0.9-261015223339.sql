-- 回收 super(role_id=200) 的两个按钮权限点：
--   1005 system:user:import   用户导入
--   1006 system:user:resetPwd 重置密码
--
-- 背景：
--   super 等部门管理员创建的账号统一走「登录手机号 + 短信验证码」体系：
--     · 新建用户时禁止指定密码（后端 SysUserController.add 强制随机强密码）；
--     · Excel 导入的新用户一律使用初始密码，无法实施上述策略，后端已直接拒绝
--       非平台管理员导入，前端按钮同步隐藏（回收 1005）；
--     · 重置他人密码仅限平台内置管理员(userId=1)，后端 resetPwd 已加硬闸，
--       前端菜单项同步隐藏（回收 1006）。
--   个人中心凭旧密码修改本人密码不受影响（不走 system:user:resetPwd）。
--
-- 注意：权限点回收仅做 UI 收敛，最终拦截在 Controller（不依赖登录态内缓存的
--       权限集合是否刷新）；执行后 super 重新登录菜单/按钮即与后端一致。
--
-- 幂等：DELETE 可重复执行，不存在不报错。
-- ======================================================================

SET NAMES utf8mb4;

DELETE FROM sys_role_menu
 WHERE role_id = 200
   AND menu_id IN (1005, 1006);

