    <!-- 生成按钮 -->
    <el-row :gutter="10" class="mb8">
      <el-col :span="1.5">
        <el-button type="primary" plain icon="Plus" @click="showGenDialog = true" v-hasPermi="['apms:report:generate']">
          生成新报告
        </el-button>
      </el-col>
    </el-row>

    <!-- 主从两栏 -->
    <el-row :gutter="16">
      <!-- 左：报告列表 -->
      <el-col :span="10">
        <div class="panel-title">
          <span>PDF 报告</span>
          <span class="panel-sub">共 {{ total }} 份 · 历史可复现</span>
        </div>
        <el-table :data="reportList" border stripe highlight-current-row
                  v-loading="loading" max-height="600" @row-click="handleRowClick">
          <el-table-column label="#" prop="id" width="50" align="center"/>
          <el-table-column label="类型" width="110">
            <template #default="scope">
              <el-tag :type="typeTag(scope.row.reportType)" size="small" effect="dark">
                {{ typeLabel(scope.row.reportType) }}
              </el-tag>
            </template>
          </el-table-column>
          <el-table-column label="主体" min-width="140">
            <template #default="scope">
              <span class="subject">{{ scope.row.athleteName || scope.row.taskName || scope.row.deptName || '—' }}</span>
            </template>
          </el-table-column>
          <el-table-column label="生成时间" width="160">
            <template #default="scope">{{ formatDateTime(scope.row.generateTime) }}</template>
          </el-table-column>
          <el-table-column label="版本" width="80" align="center">
            <template #default="scope" class="ver">{{ scope.row.templateVersion }}</template>
          </el-table-column>
          <el-table-column label="操作" width="120" fixed="right">
            <template #default="scope">
              <el-button link type="primary" icon="Download" @click.stop="handleDownload(scope.row)" v-hasPermi="['apms:report:download']">
                下载
              </el-button>
              <el-button link type="danger" icon="Delete" @click.stop="handleDelete(scope.row)" v-hasPermi="['apms:report:remove']">删</el-button>
            </template>
          </el-table-column>
        </el-table>
        <pagination v-show="total>0" :total="total" v-model:page="queryParams.pageNum" v-model:limit="queryParams.pageSize" @pagination="getList"/>
      </el-col>

      <!-- 右：详情侧栏 -->
      <el-col :span="14">
