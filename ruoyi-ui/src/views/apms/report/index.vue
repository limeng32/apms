<script setup name="ApmsReport">
import { listReport, getReport, generateReport, delReport, downloadReportUrl } from '@/api/apms/report'
import { listTestTask } from '@/api/apms/testTask'
import { listAthlete } from '@/api/apms/athlete'
import { listDept } from '@/api/system/dept'
import { UploadFilled } from '@element-plus/icons-vue'

const { proxy } = getCurrentInstance()

// ========= 字典 =========
const typeOpts = [
  { v: 'INDIVIDUAL', label: '单人综合' },
  { v: 'TASK',       label: '任务报告' },
  { v: 'TEAM',       label: '队伍汇总' }
]
function typeLabel(t) { return typeOpts.find(x => x.v === t)?.label || t }
function typeTag(t) { return ({ INDIVIDUAL: 'primary', TASK: 'success', TEAM: 'warning' })[t] || 'info' }

// ========= 查询 =========
const loading = ref(false)
const reportList = ref([])
const total = ref(0)
const queryParams = reactive({ pageNum: 1, pageSize: 10, reportType: null })

function getList() {
  loading.value = true
  listReport(queryParams).then(r => { reportList.value = r.rows; total.value = r.total; loading.value = false })
}
function handleQuery() { queryParams.pageNum = 1; getList() }
function resetQuery() { proxy.resetForm('queryForm'); handleQuery() }

// ========= 辅助下拉 =========
const athleteOpts = ref([]), taskOpts = ref([]), deptOpts = ref([])
listAthlete({ pageNum: 1, pageSize: 300 }).then(r => { athleteOpts.value = r.rows || [] })
listTestTask({ pageNum: 1, pageSize: 200 }).then(r => { taskOpts.value = r.rows || [] })
listDept({ pageNum: 1, pageSize: 500 }).then(r => { deptOpts.value = r.data || [] })

// ========= 主从 =========
const current = ref(null)
function handleRowClick(row) {
  current.value = row
  getReport(row.id).then(r => { current.value = r.data })
}

// ========= 生成 =========
const showGenDialog = ref(false)
const genLoading = ref(false)
const genForm = reactive({ reportType: 'INDIVIDUAL', athleteId: null, taskId: null, deptId: null })
const genRules = {
  INDIVIDUAL: [{ required: true, message: '请选运动员', trigger: 'change' }],
  TASK:       [{ required: true, message: '请选测试任务', trigger: 'change' }],
  TEAM:       [{ required: true, message: '请选队伍', trigger: 'change' }]
}

function submitGen() {
  genLoading.value = true
  const params = { reportType: genForm.reportType }
  if (genForm.athleteId) params.athleteId = genForm.athleteId
  if (genForm.taskId) params.taskId = genForm.taskId
  if (genForm.deptId) params.deptId = genForm.deptId
  generateReport(params).then(() => {
    proxy.$modal.msgSuccess('报告生成成功 📄')
    showGenDialog.value = false
    getList()
  }).finally(() => { genLoading.value = false })
}

// ========= 操作 =========
function handleDownload(row) {
  // RuoYi 前端拦截器自动加 Token — 直接 window.open
  const token = localStorage.getItem('Admin-Token')
  if (token) {
    // 用 fetch 下载更可靠（带 Authorization header）
    fetch(downloadReportUrl(row.id), {
      headers: { 'Authorization': 'Bearer ' + token }
    }).then(r => r.blob()).then(blob => {
      const a = document.createElement('a')
      const url = URL.createObjectURL(blob)
      a.href = url; a.download = row.filePath?.split('/').pop() || 'report.pdf'
      a.click(); URL.revokeObjectURL(url)
    })
  } else {
    window.open(downloadReportUrl(row.id), '_blank')
  }
}

function handleDelete(row) {
  proxy.$modal.confirm('确认删除该报告？PDF 文件一并清理。').then(() => {
    delReport(row.id).then(() => {
      proxy.$modal.msgSuccess('已删除'); getList()
      if (current.value?.id === row.id) current.value = null
    })
  }).catch(() => {})
}

function formatSnapshot(snap) {
  if (!snap) return '(empty)'
  try {
    const obj = JSON.parse(snap)
    return JSON.stringify(obj, null, 2)
  } catch { return snap }
}
function formatDateTime(d) { if (!d) return ''; return String(d).substring(0, 19).replace('T', ' ') }

getList()
</script>

