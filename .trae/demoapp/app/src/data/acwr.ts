/**
 * acwr.ts — 急慢性负荷比（ACWR）序列
 * 对应 mock-data.md §3
 * 13 个周点：2025-03-24 当周 → 2025-06-16 当周（本周进行中）
 */

export interface AcwrPoint {
  /** 周一日期 */
  week: string;
  /** 急性负荷（本周，AU = sRPE×分钟） */
  acute: number;
  /** 慢性负荷（近 4 周均值，AU） */
  chronic: number;
  /** 急慢性负荷比 */
  acwr: number;
}

export const ACWR_WEEKS: string[] = [
  '2025-03-24', '2025-03-31', '2025-04-07', '2025-04-14', '2025-04-21', '2025-04-28',
  '2025-05-05', '2025-05-12', '2025-05-19', '2025-05-26', '2025-06-02', '2025-06-09',
  '2025-06-16',
];

/** 本周（当前周，进行中） */
export const CURRENT_WEEK = '2025-06-16';

/** ACWR 分区定义 */
export const ACWR_ZONES = [
  { min: 0, max: 0.8, label: '负荷不足', status: 'amber' as const },
  { min: 0.8, max: 1.3, label: '最佳区间', status: 'green' as const },
  { min: 1.3, max: 1.5, label: '高风险', status: 'amber' as const },
  { min: 1.5, max: 2.2, label: '危险', status: 'red' as const },
];

function series(acute: number[], acwr: number[]): AcwrPoint[] {
  return ACWR_WEEKS.map((week, i) => ({
    week,
    acute: acute[i],
    chronic: Math.round(acute[i] / acwr[i]),
    acwr: acwr[i],
  }));
}

